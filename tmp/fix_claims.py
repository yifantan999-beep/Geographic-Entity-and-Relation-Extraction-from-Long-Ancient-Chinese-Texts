def font(run,name="宋体",size=12,bold=False):
    run.font.name=name
    rpr=run._element.get_or_add_rPr()
    rpr.rFonts.set(qn("w:eastAsia"),name)
    rpr.rFonts.set(qn("w:ascii"),"Times New Roman")
    rpr.rFonts.set(qn("w:hAnsi"),"Times New Roman")
    run.font.size=Pt(size); run.bold=bold
def para(text,center=False,bold=False):
    x=doc.add_paragraph()
    x.alignment=WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    x.paragraph_format.first_line_indent=Mm(0 if center else 8)
    x.paragraph_format.line_spacing=1.5
    font(x.add_run(text),bold=bold)
    return x
